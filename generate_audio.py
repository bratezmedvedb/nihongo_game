def generate_voicevox_audio(word_id, text):
    file_path = os.path.join(OUTPUT_DIR, f"{word_id}.mp3")
    if os.path.exists(file_path):
        print(f"[{word_id}] Пропущен (уже создан)")
        return

    clean_text = text.replace("〜", "").replace("—", "").replace("-", "").strip()
    if not clean_text:
        return

    try:
        query_res = requests.post(
            f"{VOICEVOX_URL}/audio_query",
            params={"text": clean_text, "speaker": SPEAKER_ID},
            timeout=10
        )
        query_data = query_res.json()
        query_data["speedScale"] = 0.85

        synth_res = requests.post(
            f"{VOICEVOX_URL}/synthesis",
            params={"speaker": SPEAKER_ID},
            json=query_data,
            timeout=10
        )

        with open(file_path, "wb") as f:
            f.write(synth_res.content)

        print(f"✅ [{word_id}/830] Готово: {clean_text}")
    except Exception as e:
        print(f"❌ Ошибка [{word_id}]: {e}")

